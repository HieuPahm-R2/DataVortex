"""Keep Dataform operations generated from the accepted warehouse SQL owner."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'warehouse/dataform/includes/campaign_sql.js'


def generated():
    sql = (ROOT / 'warehouse/bigquery/publish_campaign.sql').read_text(encoding='utf-8')
    quality = sql.split('BEGIN TRANSACTION;', 1)[0]
    return '// Generated by scripts/sync_dataform.py from warehouse/bigquery/publish_campaign.sql.\nmodule.exports = ' + json.dumps(
        {'quality': quality, 'publish': sql}, ensure_ascii=False, indent=2) + ';\n'


def check(path=TARGET):
    if not path.exists() or path.read_text(encoding='utf-8') != generated():
        raise ValueError(f'{path}: Dataform SQL differs from warehouse/bigquery/publish_campaign.sql; '
                         'run python -m scripts.sync_dataform, then validate again.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = generated()
    if args.check:
        try:
            check()
        except ValueError as error:
            raise SystemExit(str(error))
    else:
        TARGET.write_text(expected, encoding='utf-8', newline='\n')
